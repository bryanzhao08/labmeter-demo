r=E.reconcile([{...b,e:s+60}],[{...u,s,e:s+48}],{...p,basis:'actual'})[0];assert.equal(r.billed,60);
r=E.reconcile([b],[{...u,s,e:s+180}],p)[0];assert.equal(r.billed,180,'overlap counted once');
