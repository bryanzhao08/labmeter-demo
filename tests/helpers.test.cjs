'use strict';
const assert = require('node:assert/strict');
const h = require('../helpers.js');
globalThis.LBRates = require('../ratesheet.js');

assert.deepEqual(h.extractMachines('two analyzers, a cell sorter and a confocal'), ['Analyzer 1', 'Analyzer 2', 'Cell sorter', 'Confocal']);
assert.deepEqual(h.extractMachines('We have friendly staff.'), []);
assert.deepEqual(h.extractMachines('The cell sorter is billed on actual time'), ['Cell sorter']);
assert.deepEqual(h.machineRulesFrom('The cell sorter is billed on actual time and rounded to 15 minutes.', ['Cell sorter', 'Confocal']), {'Cell sorter': {billing: 'Used only', round_minutes: 15}});
assert.deepEqual(h.ratesFrom('Self-service $60/hr; assisted $125/hr; training $80/hr'), {self: 60, assisted: 125, training: 80});
assert.deepEqual(h.ratesFrom('$75 per hour self-service'), {self: 75});
for (const [text, kind] of [['Use exceeded the booked time', 'time'], ['Missing or multiple labs', 'who'], ['Unusually long session', 'unusual'], ['Invalid date', 'data']]) assert.equal(h.flagKind(text), kind);

const profile = {basis: 'union', evidence: 'login', round_minutes: 30, rates: {self: 50, assisted: 100, training: 80}, machine_rules: {'Cell sorter': {billing: 'Acquisition time', round_minutes: 15, rates: {self: 65}}}};
assert.deepEqual(h.policyFor(profile, 'Confocal'), {basis: 'union', evidence: 'login', round: 30, rates: profile.rates, defaultTier: 'internal'});
assert.deepEqual(h.policyFor(profile, 'cell sorter'), {basis: 'actual', evidence: 'acquisition', round: 15, rates: {self: 65, assisted: 100, training: 80}, defaultTier: 'internal'});
const cardProfile = {...profile, tiers: [{key: 'internal'}, {key: 'external'}], after_hours: {start: 19, end: 8, weekends: false}, rate_card: [{machine: 'Confocal', mode: 'self', hourly: true, rates: {internal: 70, external: 110}, after: {internal: 90, external: 140}}]};
const policy = h.policyFor(cardProfile, 'Confocal');
assert.equal(policy.rateFor('self', 'university', false), 70);
assert.equal(policy.rateFor('self', 'external academic', false), 110);
assert.equal(policy.rateFor('self', 'external', true), 140);
assert.deepEqual(policy.afterHours, {start: 19, end: 8, weekends: false});
assert.deepEqual(h.outliers([1, 2, 3, 4, 5, 6, 30].map(billed => ({billed}))), []);
const rows = [9, 10, 10, 11, 11, 12, 12, 100].map(billed => ({billed}));
assert.deepEqual(h.outliers(rows), [rows[7]]);
assert.deepEqual(h.dedupeMachines(['Analyzer 1', 'analyzers', 'Confocal', 'confocal 2']), ['Analyzer 1', 'Confocal']);
assert.deepEqual(h.dedupeMachines(['Cell sorter', 'BD Cell sorter', 'Confocal'], ['BD Cell sorter']), ['BD Cell sorter', 'Confocal']);
assert.equal(h.tierKey(' Campus '), 'internal');
assert.equal(h.tierKey('Outside academic'), 'external');
assert.equal(h.tierKey('For-profit'), 'commercial');
assert.equal(h.tierKey('Partner', ['partner']), 'partner');
assert.equal(h.tierKey(''), '');
const draft = {machines: ['Cell sorter', 'Confocal'], machines_on: ['Cell sorter'], rates: {self: 1, assisted: 2, training: 3}, default_tier: 'missing'};
const parsed = {items: [{machine: 'BD Cell sorter', mode: 'self', hourly: true, rates: {internal: 60}, after: {}}, {machine: '', mode: 'training', hourly: true, rates: {internal: 95}, after: {}}, {machine: 'Sample prep', mode: 'any', hourly: false, rates: {internal: 10}, after: {}}], tiers: [{key: 'external'}], after_hours: {start: 18, end: 9, weekends: true}, round_minutes: 15, notes: ['Round up']};
assert.equal(h.applyRateCard(draft, parsed), draft);
assert.deepEqual(draft.machines, ['BD Cell sorter', 'Confocal']);
assert.deepEqual(draft.machines_on, ['BD Cell sorter']);
assert.equal(draft.rates.training, 95);
assert.equal(draft.default_tier, 'external');
assert.equal(draft.round_minutes, 15);
assert.deepEqual(draft.after_hours, parsed.after_hours);
assert.deepEqual(draft.price_notes, ['Round up']);
assert.equal(draft.rate_card, parsed.items);
console.log('helpers tests pass');
